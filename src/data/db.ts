import Dexie, { type EntityTable } from 'dexie'
import dexieCloud from 'dexie-cloud-addon'
import type { PlannedMeal } from '../engine/plan'
import type { Profile } from '../engine/profile'
import type { Recipe } from '../engine/types'
import type { ImportedRecipe } from './importRecipes'

export interface StoredRecipe extends Recipe {
  /** Bundled demo recipe (never stored, see defaults.ts). */
  sample?: boolean
}

export interface StoredMeal extends PlannedMeal {
  id: string
}

/** A ticked-off item on the shopping list, by product name. */
export interface ShoppingCheck {
  id: string
  name: string
}

/** A recipe's photo, kept apart from recipes so that listing recipes doesn't load every image. */
export interface RecipeImage {
  id: string
  recipeId: string
  blob: Blob
}

// Dexie Cloud syncs this database when the user logs in, so primary keys must be globally unique:
// "@id" keys are generated by the addon, profiles use ids tied to their realm (see household.ts).
// Samples and default profiles are never stored, otherwise every new device would add copies.
export const db = new Dexie('makromenu-cloud', { addons: [dexieCloud] }) as Dexie & {
  recipes: EntityTable<StoredRecipe, 'id'>
  profiles: EntityTable<Profile, 'id'>
  mealPlan: EntityTable<StoredMeal, 'id'>
  shoppingChecks: EntityTable<ShoppingCheck, 'id'>
  recipeImages: EntityTable<RecipeImage, 'id'>
  // realms, members and roles are typed by dexie-cloud-addon.
}

db.version(1).stores({
  recipes: '@id, slug, name',
  profiles: 'id',
  mealPlan: '@id, date',
  shoppingChecks: '@id, name',
  recipeImages: '@id, recipeId',
})
// Access control tables of Dexie Cloud (realms and their members); names and keys are fixed by the addon.
db.version(2).stores({
  realms: '@realmId',
  members: '@id, realmId, userId, [email+realmId]',
  roles: '[realmId+name]',
})

/** Cloud sync is available when the build knows the database URL; without it the app is local only. */
export const CLOUD_URL: string | undefined = import.meta.env.VITE_DEXIE_CLOUD_URL

// Browser tests log in demo users through this; development builds only.
if (import.meta.env.DEV) Object.assign(window, { db })

if (CLOUD_URL) {
  db.cloud.configure({
    databaseUrl: CLOUD_URL,
    // Logging in is optional: without an account the data stays on the device.
    requireAuth: false,
    customLoginGui: true,
    socialAuth: false,
  })
}

/** Photos as Blobs. Done before writing, since a transaction can't wait for anything but the database. */
export function imageBlobs(recipes: ImportedRecipe[]): Promise<(Blob | undefined)[]> {
  return Promise.all(recipes.map((r) => (r.image ? fetch(r.image).then((res) => res.blob()) : undefined)))
}

/**
 * Stores imported recipes, matched to stored ones by slug: a recipe imported again is updated, but
 * meal types set by hand in the app are kept unless the file has its own. A photo replaces the
 * recipe's previous one. Must run in a transaction over recipes and recipeImages.
 * Returns the database id of every recipe by its id in the file.
 */
export async function writeRecipes(recipes: ImportedRecipe[], blobs: (Blob | undefined)[]): Promise<Map<string, string>> {
  const slugs = recipes.map((r) => r.slug ?? r.id)
  const existing = new Map((await db.recipes.where('slug').anyOf(slugs).toArray()).map((r) => [r.slug, r]))
  const ids: string[] = []
  for (const [i, recipe] of recipes.entries()) {
    const old = existing.get(slugs[i])
    const row: Partial<StoredRecipe & ImportedRecipe> = { ...recipe, slug: slugs[i], mealTypes: recipe.mealTypes ?? old?.mealTypes }
    // The file's id is the slug, the database id is generated by Dexie Cloud; the photo goes to its own table.
    delete row.id
    delete row.image
    ids.push(old ? (await db.recipes.put({ ...(row as StoredRecipe), id: old.id })) : await db.recipes.add(row as StoredRecipe))
  }
  for (const [i, blob] of blobs.entries()) {
    if (!blob) continue
    await db.recipeImages.where('recipeId').equals(ids[i]).delete()
    await db.recipeImages.add({ recipeId: ids[i], blob } as RecipeImage)
  }
  return new Map(recipes.map((r, i) => [r.id, ids[i]]))
}

export async function saveImportedRecipes(recipes: ImportedRecipe[]): Promise<void> {
  const blobs = await imageBlobs(recipes)
  await db.transaction('rw', db.recipes, db.recipeImages, () => writeRecipes(recipes, blobs))
}
